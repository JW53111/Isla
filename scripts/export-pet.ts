// Same formula as the renderer's — used only to pre-size the window at startup
function computeScale(workAreaHeight, s) {
  const ratio = clamp(s.autoScaleRatio != null ? s.autoScaleRatio : 0.2, 0.08, 0.45);
  const targetH = clamp(workAreaHeight * ratio, 80, Math.min(420, workAreaHeight * 0.5));
  return (targetH * clamp(s.zoom != null ? s.zoom : 1, 0.5, 2.5)) / STAGE_HEIGHT;
}

function restorePosition(width, height) {
  const pos = settings.position;
  let d = null;
  if (pos && pos.displayId) {
    d = screen.getAllDisplays().find(function (dd) { return dd.id === pos.displayId; }) || null;
  }
  if (!d) d = screen.getPrimaryDisplay();
  const wa = d.workArea;
  let x, y;
  if (pos && pos.rx != null && pos.ry != null) {
    x = wa.x + pos.rx * Math.max(wa.width - width, 1);
    y = wa.y + pos.ry * Math.max(wa.height - height, 1);
  } else {
    x = wa.x + wa.width - width - 80;
    y = wa.y + Math.round(wa.height * 0.55);
  }
  return { x: Math.round(x), y: Math.round(y), displayId: d.id };
}

// getDisplayMatching 在个别 Windows 环境（启动瞬间/DPI 变化时）会抛
// 「Error processing argument at index 0, conversion failure」——捕获后回退主显示器，
// 现场写进 error.log，不再弹系统错误对话框
function safeDisplayMatching(bounds) {
  try {
    // getDisplayMatching 要求整数参数：渲染层算出的坐标常带 .5 小数（窗口居中除 2），
    // 直接传入会抛「conversion failure」——先取整
    return screen.getDisplayMatching({
      x: Math.round(Number(bounds.x) || 0),
      y: Math.round(Number(bounds.y) || 0),
      width: Math.round(Number(bounds.width) || 0),
      height: Math.round(Number(bounds.height) || 0),
    });
  } catch (e) {
    logError('getDisplayMatching failed, bounds=' + JSON.stringify(bounds), e);
    return screen.getPrimaryDisplay();
  }
}

function clampToWorkArea(b) {
  // 参数先做数值化防护：渲染层可能传入非法值，直接进原生 API 会弹「conversion failure」报错
  const x0 = Number(b.x);
  const y0 = Number(b.y);
  const w0 = Number(b.width) || STAGE_WIDTH;
  const h0 = Number(b.height) || STAGE_HEIGHT;
  const d = safeDisplayMatching({ x: isFinite(x0) ? x0 : 0, y: isFinite(y0) ? y0 : 0, width: w0, height: h0 });
  const wa = d.workArea;
  const x = clamp(isFinite(x0) ? x0 : 0, wa.x - w0 + 40, wa.x + wa.width - 40);
  let y;
  if (wa.height - 40 < h0) {
    y = wa.y;
  } else {
    y = clamp(isFinite(y0) ? y0 : 0, wa.y, wa.y + wa.height - 40);
  }
  return { x: Math.round(x), y: Math.round(y), width: w0, height: h0 };
}

function createWindow() {
  let d = null;
  if (settings.position && settings.position.displayId) {
    d = screen.getAllDisplays().find(function (dd) { return dd.id === settings.position.displayId; }) || null;
  }
  if (!d) d = screen.getPrimaryDisplay();
  const scale = computeScale(d.workArea.height, settings);
  const width = Math.round(STAGE_WIDTH * scale);
  const height = Math.round(STAGE_HEIGHT * scale);
  const pos = restorePosition(width, height);
  petWindow = new BrowserWindow({
    x: pos.x, y: pos.y,
    width: width, height: height,
    transparent: true, frame: false, alwaysOnTop: true,
    skipTaskbar: false, resizable: false, hasShadow: false,
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true, nodeIntegration: false,
    },
  });
  petWindow.loadFile(path.join(__dirname, 'renderer', 'index.html'));
  attachErrorCapture(petWindow, 'pet');
  petWindow.setVisibleOnAllWorkspaces(true, { visibleOnFullScreen: true });
  petWindow.setAlwaysOnTop(true, 'screen-saver');
  petWindow.on('closed', function () { petWindow = null; });
  petWindow.on('move', debounce(function () { checkDisplayChange(); savePosition(); }, 300));
}

function currentDisplayConfig() {
  const d = petWindow ? safeDisplayMatching(petWindow.getBounds()) : screen.getPrimaryDisplay();
  return {
    displayId: d.id,
    workArea: { x: d.workArea.x, y: d.workArea.y, width: d.workArea.width, height: d.workArea.height },
    scaleFactor: d.scaleFactor,
  };
}

function checkDisplayChange() {
  const cfg = currentDisplayConfig();
  const key = cfg.displayId + ':' + cfg.workArea.width + 'x' + cfg.workArea.height;
  if (key !== lastDisplayKey) {
    lastDisplayKey = key;
    if (petWindow && !petWindow.isDestroyed()) {
      petWindow.webContents.send('display-config-changed', cfg);
    }
  }
}

function savePosition() {
  if (!petWindow || petWindow.isDestroyed()) return;
  const [x, y] = petWindow.getPosition();
  const [w, h] = petWindow.getSize();
  const d = safeDisplayMatching({ x: x, y: y, width: w, height: h });
  const wa = d.workArea;
  settings.position = {
    displayId: d.id,
    rx: (x - wa.x) / Math.max(wa.width - w, 1),
    ry: (y - wa.y) / Math.max(wa.height - h, 1),
  };
  saveSettings();
}

