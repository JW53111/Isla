  const wa = screen.getPrimaryDisplay().workArea;
  const [w, h] = petWindow.getSize();
  petWindow.setBounds(clampToWorkArea({ x: wa.x + wa.width - w - 80, y: wa.y + wa.height - h - 40, width: w, height: h }));
