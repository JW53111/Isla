// 渲染进程崩溃/加载失败/报错 → error.log（这类错误默认静默不可见）
function attachErrorCapture(win, tag) {
  if (!win || win.isDestroyed()) return;
  win.webContents.on('render-process-gone', function (_e, details) {
    logError(tag + ':render-process-gone', JSON.stringify(details));
  });
  win.webContents.on('did-fail-load', function (_e, code, desc, url) {
    logError(tag + ':did-fail-load', code + ' ' + desc + ' ' + url);
  });
  win.webContents.on('console-message', function (_e, level, message, line, sourceId) {
    if (level >= 3) logError(tag + ':console', message + ' (' + sourceId + ':' + line + ')');
  });
}

