// ---- global shortcuts ----
function registerShortcuts() {
  const SHORTCUTS = [
    ['Ctrl+Shift+B', toggleVisible],
    ['Ctrl+Shift+Left', function () { sendCommand('zoom-out'); }],
    ['Ctrl+Shift+Right', function () { sendCommand('zoom-in'); }],
    ['Ctrl+Shift+Up', function () { setOpacity(settings.opacity + 0.1); }],
    ['Ctrl+Shift+Down', function () { setOpacity(settings.opacity - 0.1); }],
    ['Ctrl+Shift+R', resetPosition],
    ['Ctrl+Shift+Q', function () { app.quit(); }],
  ];
  for (const pair of SHORTCUTS) {
    if (!globalShortcut.register(pair[0], pair[1])) {
      console.warn('[pet] 快捷键注册失败（可能被其他程序占用）：' + pair[0]);
    }
  }
}

