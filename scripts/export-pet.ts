function loadJson(name, fallback) {
  try {
    const p = path.join(userDataDir, name);
    if (!fs.existsSync(p)) return fallback;
    return Object.assign({}, fallback, JSON.parse(fs.readFileSync(p, 'utf-8')));
  } catch (e) {
    try {
      fs.renameSync(path.join(userDataDir, name), path.join(userDataDir, name + '.bak'));
    } catch (e2) { /* ignore */ }
    return fallback;
  }
}

