ipcMain.on('resize-window', function (_event, width, height) {
  if (!petWindow) return;
  width = Number(width);
  height = Number(height);
  if (!isFinite(width) || !isFinite(height) || width <= 0 || height <= 0) return;
  const [x, y] = petWindow.getPosition();
  const [w, h] = petWindow.getSize();
  // horizontal centering + bottom anchor (feet stay put, no jumping)
  petWindow.setBounds(clampToWorkArea({
    x: x + (w - width) / 2,
    y: y + (h - height),
    width: Math.round(width),
    height: Math.round(height),
  }));
});

ipcMain.on('move-window', function (_event, dx, dy, opts) {
  if (!petWindow) return;
  dx = Number(dx);
  dy = Number(dy);
  if (!isFinite(dx) || !isFinite(dy)) return;
  const [x, y] = petWindow.getPosition();
  let nx = x + dx;
  let ny = y + dy;
  if (opts && opts.clamp) {
    const [w, h] = petWindow.getSize();
    const b = clampToWorkArea({ x: nx, y: ny, width: w, height: h });
    nx = b.x;
    ny = b.y;
  }
  petWindow.setPosition(Math.round(nx), Math.round(ny));
});

